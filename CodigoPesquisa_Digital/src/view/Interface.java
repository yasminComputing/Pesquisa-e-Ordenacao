/**
 * Metódo que tem como objetivo destacar em AMARELO as palavras digitadas no campo de pesquisar
 * @param palavra: utilizado como parâmetro para buscar as palavras dentro do arquivo 
 */
    private void destacarPalavraPesquisa(String palavra){
        Highlighter destaque = txta_Texto.getHighlighter();
        
        destaque.removeAllHighlights();
        
        if(palavra.isEmpty()){
            return;
        }
        String texto = txta_Texto.getText();
        Highlighter.HighlightPainter pintor = new DefaultHighlighter.DefaultHighlightPainter(Color.YELLOW);
        
        for(int i = 0; (i + palavra.length()) <= texto.length(); i++){
            if(texto.substring(i, i + palavra.length()).equalsIgnoreCase(palavra)){
                try{
                    destaque.addHighlight(i, i + palavra.length(), pintor);
                }catch(BadLocationException e){
                    JOptionPane.showMessageDialog(null,"Erro ao destacar a palavra/letra","Alerta",JOptionPane.ERROR_MESSAGE);
                }
            }
        }
        
    }
