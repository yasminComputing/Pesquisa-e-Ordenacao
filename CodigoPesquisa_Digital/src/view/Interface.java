    private void txt_PesquisaKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_PesquisaKeyTyped
        char c = evt.getKeyChar();

        if (!Character.isISOControl(c)) {
            palavraDigitada.append(c);
        } else {
            palavraDigitada = new StringBuffer(txt_Pesquisa.getText());
        }

        ocorrencias = 0;

        String palavra = txt_Pesquisa.getText() + evt.getKeyChar();
        String texto = txta_Texto.getText();

        if (!palavra.isEmpty()) {
            for (int i = 0; i + palavra.length() <= texto.length(); i++) {
                if (texto.substring(i, i + palavra.length()).equalsIgnoreCase(palavra)) {
                    ocorrencias++;
                }
            }
        }
        txtOcorrencia.setText(String.valueOf(ocorrencias));
        destacarPalavraPesquisa(palavra);//chama o método destacar palavra
    }//GEN-LAST:event_txt_PesquisaKeyTyped

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        Arquivo arquivo = new Arquivo();
        lista.clear();
        if(!arquivo.carregarArquivo(txtNomeArquivo.getText(),lista)){
            JOptionPane.showMessageDialog(this,"Erro ao carregar arquivo!","Alerta",JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        txta_Texto.setText("");
        //percorre cada elemento da lista
        for (String linha : lista) {
            txta_Texto.append(linha + "\n");//adiciona no textArea o contéudo 
        }
        pnl_Pesquisa.setVisible(true);
    }//GEN-LAST:event_btnBuscarActionPerformed

